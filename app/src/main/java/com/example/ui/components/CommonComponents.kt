@Composable
fun SalesBarChart(
    points: List<Pair<String, Double>>,
    modifier: Modifier = Modifier
) {
    val primary = MaterialTheme.colorScheme.primary
    val secondary = MaterialTheme.colorScheme.secondary
    val track = MaterialTheme.colorScheme.surfaceVariant
    val maxVal = (points.maxOfOrNull { it.second } ?: 0.0).coerceAtLeast(1.0)

    ElevatedCard(
        modifier = modifier.fillMaxWidth(),
        colors = CardDefaults.elevatedCardColors(containerColor = MaterialTheme.colorScheme.surface)
    ) {
        Column(modifier = Modifier.padding(16.dp)) {
            Text(
                text = "7-Day Sales Pulse",
                style = MaterialTheme.typography.titleSmall,
                fontWeight = FontWeight.Bold
            )
            Spacer(modifier = Modifier.height(12.dp))
            Canvas(
                modifier = Modifier
                    .fillMaxWidth()
                    .height(110.dp)
            ) {
                val count = points.size.coerceAtLeast(1)
                val barSlot = size.width / count
                val barWidth = (barSlot * 0.48f).coerceAtMost(36.dp.toPx())
                points.forEachIndexed { idx, (_, value) ->
                    val left = idx * barSlot + (barSlot - barWidth) / 2f
                    drawRoundRect(
                        color = track,
                        topLeft = Offset(left, 0f),
                        size = Size(barWidth, size.height),
                        cornerRadius = CornerRadius(12f, 12f)
                    )
                    val ratio = (value / maxVal).toFloat().coerceIn(0f, 1f)
                    val filledH = (size.height * ratio).coerceAtLeast(if (value > 0) 8f else 0f)
                    if (filledH > 0f) {
                        drawRoundRect(
                            brush = Brush.verticalGradient(listOf(secondary, primary)),
                            topLeft = Offset(left, size.height - filledH),
                            size = Size(barWidth, filledH),
                            cornerRadius = CornerRadius(12f, 12f)
                        )
                    }
                }
            }
            Spacer(modifier = Modifier.height(6.dp))
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceAround
            ) {
                points.forEach { (label, _) ->
                    Text(
                        text = label,
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                }
            }
        }
    }
}
